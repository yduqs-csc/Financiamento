SELECT CASE    WHEN UPPER(TRIM(substr(CURSO, instr(CURSO, '-')+1, 60))) = 'MEDICINA' THEN 'IDOMED'
               WHEN LOCAL_OFERTA = '1108141 - CITTÁ' AND CURSO LIKE '%ODONTOLOGIA%' THEN 'IDOMED'
                         WHEN IES LIKE '%FAMETRO%'  THEN 'UNIFAMETRO'
                         WHEN IES LIKE '%WYDEN' THEN 'WYDEN'
                         WHEN LOCAL_OFERTA LIKE '%WYDEN' THEN 'WYDEN'
                         WHEN (MANTENEDORA LIKE '%IBMEC%') AND (UPPER(LOCAL_OFERTA) LIKE '%POLO INDUSTRIAL%') THEN 'WYDEN'
                         WHEN MANTENEDORA LIKE '%IBMEC%' THEN 'IBMEC'
                         WHEN REPLACE(IES,'Á','A') LIKE '%ESTACIO%' THEN 'ESTACIO'
         END AS MARCA
         FROM (
         SELECT NULL AS MANTENEDORA , NULL AS IES, NULL AS LOCAL_OFERTA, NULL AS CURSO
         );